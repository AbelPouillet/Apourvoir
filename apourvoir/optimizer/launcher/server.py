"""
HTTP servers for the launcher (standard library only).

- API server: /health, /status, /v1/models, /v1/completions and
  /v1/chat/completions (OpenAI-compatible, non-streaming). Completions are
  generated by apourvoir.inference.InferenceEngine; without an engine they
  answer 501 Not Implemented.
- Web UI server: a small status page that reads /status.

Each server runs in a daemon thread; the launcher keeps the process alive.
"""

import json
import logging
import threading
import time
import uuid
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from typing import Any, Callable, Dict, Optional

logger = logging.getLogger(__name__)

NOT_IMPLEMENTED = {
    "error": {
        "type": "not_implemented",
        "message": "No inference engine is loaded (launcher started without one).",
    }
}


class _JSONHandler(BaseHTTPRequestHandler):
    status_provider: Callable[[], Dict[str, Any]] = staticmethod(lambda: {})
    model_name: str = ""

    def _send(self, code: int, body: bytes, content_type: str) -> None:
        self.send_response(code)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _json(self, code: int, payload: Dict[str, Any]) -> None:
        self._send(code, json.dumps(payload, default=str).encode("utf-8"), "application/json")

    def log_message(self, fmt: str, *args) -> None:
        logger.info("%s - %s", self.address_string(), fmt % args)


def _parse_sampling(body: Dict[str, Any]) -> Dict[str, Any]:
    max_tokens = int(body.get("max_tokens", 16))
    temperature = float(body.get("temperature", 0.0))
    top_p = float(body.get("top_p", 1.0))
    if not 1 <= max_tokens <= 4096:
        raise ValueError("max_tokens must be between 1 and 4096")
    if temperature < 0 or not 0 < top_p <= 1:
        raise ValueError("temperature must be >= 0 and top_p in (0, 1]")
    stop = body.get("stop")
    if isinstance(stop, str):
        stop = [stop]
    seed = body.get("seed")
    return {"max_tokens": max_tokens, "temperature": temperature, "top_p": top_p, "stop": stop,
            "seed": int(seed) if seed is not None else None}


class APIHandler(_JSONHandler):
    engine = None  # InferenceEngine or None

    def _completion(self, body: Dict[str, Any], chat: bool) -> None:
        if self.engine is None or not self.engine.ready:
            self._json(501 if self.engine is None else 503, NOT_IMPLEMENTED if self.engine is None else
                       {"error": {"type": "unavailable", "message": "inference engine is still loading"}})
            return
        if body.get("stream"):
            self._json(400, {"error": {"type": "invalid_request_error", "message": "stream is not supported"}})
            return
        try:
            params = _parse_sampling(body)
            if chat:
                messages = body.get("messages")
                if not isinstance(messages, list) or not messages:
                    raise ValueError("messages must be a non-empty list")
                result = self.engine.chat(messages, **params)
            else:
                prompt = body.get("prompt")
                if isinstance(prompt, list) and len(prompt) == 1:
                    prompt = prompt[0]
                if not isinstance(prompt, str):
                    raise ValueError("prompt must be a string")
                result = self.engine.complete(prompt, **params)
        except (ValueError, TypeError) as e:
            self._json(400, {"error": {"type": "invalid_request_error", "message": str(e)}})
            return
        except Exception as e:
            logger.exception("generation failed")
            self._json(500, {"error": {"type": "server_error", "message": str(e)}})
            return

        created = int(time.time())
        choice: Dict[str, Any] = {"index": 0, "finish_reason": result["finish_reason"]}
        if chat:
            choice["message"] = {"role": "assistant", "content": result["text"]}
            obj, prefix = "chat.completion", "chatcmpl"
        else:
            choice["text"] = result["text"]
            obj, prefix = "text_completion", "cmpl"
        self._json(200, {
            "id": f"{prefix}-{uuid.uuid4().hex[:24]}", "object": obj, "created": created,
            "model": self.engine.model_name, "choices": [choice], "usage": result["usage"],
            "apourvoir": {"quant_method": self.engine.quant_method, "generation_seconds": result["seconds"]},
        })

    def do_GET(self) -> None:
        if self.path == "/health":
            self._json(200, {"status": "ok"})
        elif self.path == "/status":
            self._json(200, self.status_provider())
        elif self.path == "/v1/models":
            self._json(200, {"object": "list", "data": [{"id": self.model_name, "object": "model"}]})
        else:
            self._json(404, {"error": {"type": "not_found", "message": self.path}})

    def do_POST(self) -> None:
        length = int(self.headers.get("Content-Length") or 0)
        raw = self.rfile.read(length) if length else b""
        if self.path in ("/v1/completions", "/v1/chat/completions"):
            try:
                body = json.loads(raw or b"{}")
                if not isinstance(body, dict):
                    raise ValueError
            except ValueError:
                self._json(400, {"error": {"type": "invalid_request_error", "message": "body must be a JSON object"}})
                return
            self._completion(body, chat=self.path == "/v1/chat/completions")
        else:
            self._json(404, {"error": {"type": "not_found", "message": self.path}})


